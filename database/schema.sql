    UPDATE_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPLAINT_ID NUMBER NOT NULL,
    STAFF_ID NUMBER NOT NULL,
    WORK_STATUS VARCHAR2(50) NOT NULL,
    DESCRIPTION VARCHAR2(1000),
