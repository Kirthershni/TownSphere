-- 3. COMPLAINT
CREATE TABLE COMPLAINT (
    COMPLAINT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    RESIDENT_ID NUMBER REFERENCES RESIDENT(RESIDENT_ID) ON DELETE CASCADE,
    CATEGORY VARCHAR2(100) NOT NULL,
    DESCRIPTION VARCHAR2(1000) NOT NULL,
    PRIORITY VARCHAR2(20) DEFAULT 'Low',
    STATUS VARCHAR2(50) DEFAULT 'Pending Worker',
    IMAGE_PATH VARCHAR2(255),
    VISIT_TIME_SLOT VARCHAR2(50) DEFAULT 'Anytime',
    IS_EMERGENCY NUMBER(1) DEFAULT 0
        CHECK (IS_EMERGENCY IN (0, 1)),
    REJECTION_REASON VARCHAR2(1000),
    CREATED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    COMPLETED_DATE TIMESTAMP
);

-- 4. ASSIGNMENT
CREATE TABLE ASSIGNMENT (
    ASSIGNMENT_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPLAINT_ID NUMBER REFERENCES COMPLAINT(COMPLAINT_ID) ON DELETE CASCADE,
    STAFF_ID NUMBER REFERENCES STAFF(STAFF_ID) ON DELETE CASCADE,
    ASSIGNED_DATE TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    ASSIGNMENT_STATUS VARCHAR2(50) DEFAULT 'Assigned',
    DECISION_DATE TIMESTAMP,
    REJECTION_REASON VARCHAR2(255)
);

-- 5. RATING
CREATE TABLE RATING (
    RATING_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    COMPLAINT_ID NUMBER REFERENCES COMPLAINT(COMPLAINT_ID) ON DELETE CASCADE,
    RATING_SCORE NUMBER CHECK (RATING_SCORE BETWEEN 1 AND 5),
    FEEDBACK VARCHAR2(1000),
    CREATED_AT DATE DEFAULT SYSDATE
);

-- 6. WORK_UPDATE
